def results_for_table(table: str) -> tuple[ReportedResult, ...]:
    return tuple(result for result in REPORTED_RESULTS if result.table == table)


def expected_result(method: str, metric: str, split: str) -> ReportedResult:
    matches = tuple(
        result
        for result in REPORTED_RESULTS
        if result.method == method and result.metric == metric and result.split == split
    )
    if len(matches) != 1:
        raise KeyError((method, metric, split))
    return matches[0]
